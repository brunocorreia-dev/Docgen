#!/usr/bin/env bash
# Builds the DocGen desktop app for Linux with jlink + jpackage:
#   target/desktop/dist/DocGen/                      app image (bundled Java runtime, no JDK needed)
#   target/desktop/dist/DocGen-<version>-linux-<arch>.tar.gz (+ .sha256)
#   optionally a .deb or .rpm (only when the native packaging tools are installed)
#
# Usage: packaging/linux/build-app-image.sh [--jdk <dir>] [--type app-image|deb|rpm] [--build] [--no-smoke-test]
#   --jdk <dir>       JDK 21+ that provides jlink and jpackage (default: $JPACKAGE_JDK, then $JAVA_HOME).
#   --type <type>     app-image (default), deb or rpm. deb needs dpkg-deb and fakeroot; rpm needs rpmbuild.
#   --build           run "mvn -B verify" first (otherwise the jars of a previous build are used).
#   --no-smoke-test   skip running the packaged launcher with --check.
#
# Nothing secret goes into the package: credentials are never configured at build time, the
# session secret is generated by the launcher at every start, and data/logs live in the user's
# profile (~/.local/share/docgen, ~/.local/state/docgen), never inside the app image.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
WORK="$ROOT/target/desktop"
JDK="${JPACKAGE_JDK:-${JAVA_HOME:-}}"
TYPE="app-image"
BUILD=0
SMOKE=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --jdk) JDK="${2:?--jdk needs a directory}"; shift 2 ;;
    --type) TYPE="${2:?--type needs app-image, deb or rpm}"; shift 2 ;;
    --build) BUILD=1; shift ;;
    --no-smoke-test) SMOKE=0; shift ;;
    -h|--help) sed -n '2,17p' "$0"; exit 0 ;;
    *) echo "build-app-image: unknown option: $1" >&2; exit 2 ;;
  esac
done

case "$TYPE" in
  app-image|deb|rpm) ;;
  *) echo "build-app-image: --type must be app-image, deb or rpm" >&2; exit 2 ;;
esac

if [[ -z "$JDK" || ! -x "$JDK/bin/jlink" || ! -x "$JDK/bin/jpackage" ]]; then
  echo "build-app-image: a JDK 21+ with jlink and jpackage is required (use --jdk or JPACKAGE_JDK)." >&2
  exit 1
fi
FEATURE="$("$JDK/bin/java" -XshowSettings:properties -version 2>&1 | awk -F' = ' '/java.specification.version/ {print $2}')"
if [[ -z "$FEATURE" || "${FEATURE%%.*}" -lt 21 ]]; then
  echo "build-app-image: $JDK is Java $FEATURE; Java 21 or newer is required." >&2
  exit 1
fi

if [[ "$BUILD" == 1 ]]; then
  (cd "$ROOT" && mvn -B verify)
fi

LAUNCHER_JAR="$ROOT/docgen-launcher/target/docgen-launcher.jar"
API_JAR="$ROOT/docgen-api/target/docgen-api.jar"
for jar in "$LAUNCHER_JAR" "$API_JAR"; do
  if [[ ! -f "$jar" ]]; then
    echo "build-app-image: $jar not found; run 'mvn -B verify' or pass --build." >&2
    exit 1
  fi
done

VERSION="$("$JDK/bin/java" -jar "$LAUNCHER_JAR" --version | awk '{print $3}')"
if [[ ! "$VERSION" =~ ^[0-9]+(\.[0-9]+){0,2}$ ]]; then
  echo "build-app-image: unexpected launcher version '$VERSION'." >&2
  exit 1
fi
case "$(uname -m)" in
  x86_64|amd64) ARCH="x64" ;;
  aarch64|arm64) ARCH="aarch64" ;;
  *) ARCH="$(uname -m)" ;;
esac

# Modules found with jdeps for the launcher and the Spring Boot API (plus charsets and pt/en
# locale data for PDF text and messages). jdk.crypto.ec holds TLS elliptic curves on Java 21.
MODULES="java.base,java.compiler,java.desktop,java.instrument,java.logging,java.management,java.naming"
MODULES="$MODULES,java.net.http,java.prefs,java.scripting,java.security.jgss,java.sql,java.sql.rowset"
MODULES="$MODULES,java.transaction.xa,java.xml,jdk.charsets,jdk.jfr,jdk.localedata,jdk.unsupported"
if "$JDK/bin/java" --list-modules | grep -q '^jdk\.crypto\.ec@'; then
  MODULES="$MODULES,jdk.crypto.ec"
fi

echo "==> Preparing $WORK"
rm -rf "$WORK"
mkdir -p "$WORK/input" "$WORK/content/backend" "$WORK/dist"

echo "==> jlink: runtime with $MODULES"
# Native commands are kept on purpose: the launcher runs the backend with lib/runtime/bin/java.
"$JDK/bin/jlink" \
  --add-modules "$MODULES" \
  --include-locales=en,pt \
  --strip-debug --no-header-files --no-man-pages \
  --compress=zip-6 \
  --output "$WORK/runtime"

# Only the launcher is the app's classpath; the API jar is app content (lib/backend), started as a child process.
cp "$LAUNCHER_JAR" "$WORK/input/docgen-launcher.jar"
cp "$API_JAR" "$WORK/content/backend/docgen-api.jar"
install -m 0644 "$SCRIPT_DIR/docgen.desktop" "$WORK/content/docgen.desktop"
"$WORK/runtime/bin/java" -Djava.awt.headless=true -cp "$WORK/input/docgen-launcher.jar" \
  com.docgen.launcher.BrandIcon "$WORK/docgen.png" 512

echo "==> jpackage: app image"
"$JDK/bin/jpackage" \
  --type app-image \
  --name DocGen \
  --app-version "$VERSION" \
  --vendor "DocGen" \
  --description "DocGen — Seu assistente local e gratuito." \
  --input "$WORK/input" \
  --main-jar docgen-launcher.jar \
  --main-class com.docgen.launcher.DocGenLauncher \
  --runtime-image "$WORK/runtime" \
  --app-content "$WORK/content/backend,$WORK/content/docgen.desktop" \
  --icon "$WORK/docgen.png" \
  --dest "$WORK/dist"

APP="$WORK/dist/DocGen"
if grep -q 'docgen-api' "$APP/lib/app/DocGen.cfg"; then
  echo "build-app-image: the API jar must not be on the launcher's classpath." >&2
  exit 1
fi

if [[ "$SMOKE" == 1 ]]; then
  echo "==> Smoke test: packaged launcher --check (isolated temporary profile)"
  SMOKE_HOME="$(mktemp -d)"
  trap 'rm -rf "$SMOKE_HOME"' EXIT
  env -u DOCGEN_API_PORT -u DOCGEN_API_PASSWORD \
    XDG_STATE_HOME="$SMOKE_HOME/state" DOCGEN_DATA_DIR="$SMOKE_HOME/data" \
    "$APP/bin/DocGen" --check
fi

ARCHIVE="DocGen-$VERSION-linux-$ARCH.tar.gz"
echo "==> Archive: $ARCHIVE"
tar -C "$WORK/dist" -czf "$WORK/dist/$ARCHIVE" DocGen
(cd "$WORK/dist" && sha256sum "$ARCHIVE" > "$ARCHIVE.sha256")

case "$TYPE" in
  deb)
    for tool in dpkg-deb fakeroot; do
      command -v "$tool" >/dev/null 2>&1 || { echo "build-app-image: --type deb needs $tool." >&2; exit 1; }
    done
    ;;
  rpm)
    command -v rpmbuild >/dev/null 2>&1 || { echo "build-app-image: --type rpm needs rpmbuild." >&2; exit 1; }
    ;;
esac
if [[ "$TYPE" != "app-image" ]]; then
  echo "==> jpackage: $TYPE"
  "$JDK/bin/jpackage" \
    --type "$TYPE" \
    --app-image "$APP" \
    --name DocGen \
    --app-version "$VERSION" \
    --vendor "DocGen" \
    --description "DocGen — Seu assistente local e gratuito." \
    --linux-package-name docgen-desktop \
    --linux-app-category devel \
    --linux-menu-group "Development" \
    --linux-shortcut \
    --dest "$WORK/dist"
fi

echo
echo "App image: $APP"
echo "Archive:   $WORK/dist/$ARCHIVE"
echo "Install for this user: packaging/linux/install-user.sh $APP"
